// already been corrupted once: UTF-8 bytes were decoded as CP1251/CP866 and
// the result was written back as UTF-8. Sources are clean now, but the values
// stay in the user database, so they are repaired on upgrade (schema v21).
//
// The repair is intentionally conservative: a string is rewritten only when
// every character maps back through a code page and the recovered bytes form
// valid UTF-8 with Cyrillic in them. Clean Russian text never satisfies that,
// so normal names stay untouched.

