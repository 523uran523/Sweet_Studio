/// Reverse maps (code point -> legacy byte), built once per table.
final List<Map<int, int>> _reverseTables = <Map<int, int>>[
  for (final table in <List<int>>[_cp1251, _cp866, _cp1252])
    _reverseTable(table),
];

Map<int, int> _reverseTable(List<int> table) {
  final map = <int, int>{};
  for (var i = 0; i < table.length; i++) {
    final cp = table[i];
    if (cp != 0) map.putIfAbsent(cp, () => 0x80 + i);
  }
  return map;
}

bool _isCyrillic(int cp) => cp >= 0x0400 && cp <= 0x04FF;

/// Russian alphabet without Ё/ё plus nothing else — anything else in the
/// Cyrillic block is double-encoding residue that cannot occur in clean text.
bool _isAlphabet(int cp) =>
    (cp >= 0x0410 && cp <= 0x044F) || cp == 0x0401 || cp == 0x0451;

bool _hasResidue(String s) {
  for (final cp in s.runes) {
    if (_isCyrillic(cp) && !_isAlphabet(cp)) return true;
  }
  return false;
}

int _cyrillicCount(String s) {
  var n = 0;
  for (final cp in s.runes) {
    if (_isCyrillic(cp)) n++;
  }
  return n;
}

/// Maps [s] back through one code page, or null when characters are outside
/// that page.
List<int>? _encodeWith(String s, Map<int, int> table) {
  final bytes = <int>[];
  for (final cp in s.runes) {
    if (cp < 0x80) {
      bytes.add(cp);
      continue;
    }
    final byte = table[cp];
    if (byte == null) return null;
    bytes.add(byte);
  }
  return bytes;
}

String? _repairOnce(String s) {
  if (!_hasResidue(s)) return null;
  for (final table in _reverseTables) {
    final bytes = _encodeWith(s, table);
    if (bytes == null) continue;
    String repaired;
    try {
      repaired = utf8.decode(bytes);
    } catch (_) {
      continue;
    }
    if (repaired == s) continue;
    if (_cyrillicCount(repaired) < 2) continue;
    return repaired;
  }
  return null;
}

/// Returns [s] with double-encoded Cyrillic restored. Text that is already
/// correct (or irrecoverably damaged) is returned unchanged.
String repairMojibake(String s) {
  if (s.isEmpty || s.contains('\uFFFD')) return s;
  String? clean;
  var current = s;
  // Some strings were corrupted twice; each pass peels one layer off.
  for (var pass = 0; pass < 3; pass++) {
    final next = _repairOnce(current);
    if (next == null || next == current) break;
    current = next;
    // Only a fully clean result is ever returned: a half-repaired string must
    // not replace a legible original.
    if (!_hasResidue(current)) {
      clean = current;
      break;
    }
  }
  return clean ?? s;
}
